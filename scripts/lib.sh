crd_exists() { k get crd "$1" >/dev/null 2>&1; }

wait_crd() {
  retry "$WAIT_TIMEOUT" 3 crd_exists "$1" || die "CRD $1 not registered after ${WAIT_TIMEOUT}s"
  k wait --for=condition=Established "crd/$1" --timeout="${WAIT_TIMEOUT}s" >/dev/null
}

# kube_apply <file|->  — kubectl apply that survives immutable StatefulSet fields
# (serviceName, volumeClaimTemplates, ...): the StatefulSet object is recreated
# with --cascade=orphan, so running pods and PVCs (data) are kept and adopted.
kube_apply() {
  local src=$1 tmp err names
  tmp=$(mktemp); err=$(mktemp)
  if [[ "$src" == - ]]; then cat >"$tmp"; else cp "$src" "$tmp"; fi
  if k apply -f "$tmp" 2>"$err" | sed 's/^/    /'; [[ ${PIPESTATUS[0]} -eq 0 ]]; then
    rm -f "$tmp" "$err"; return 0
  fi
  # Two phrasings: "The StatefulSet \"x\" is invalid" when creating, "StatefulSet.apps \"x\" is invalid"
  # when patching an existing one. No match is the normal case for any other error, and grep's exit 1
  # must not abort the script there, or the real message in $err would never be printed.
  names=$(grep -oE '(The StatefulSet|StatefulSet\.apps) "[^"]+" is invalid: spec: Forbidden' "$err" |
    cut -d'"' -f2 | sort -u || true)
  if [[ -z "$names" ]]; then
    cat "$err" >&2; rm -f "$tmp" "$err"; return 1
  fi
  local ns
  for name in $names; do
    ns=$(python3 -c '
import sys
path, name = sys.argv[1:]
for d in open(path).read().split("\n---\n"):
    if "kind: StatefulSet\n" in d and f"\n  name: {name}\n" in d:
        for line in d.splitlines():
            if line.startswith("  namespace: "): print(line.split(": ", 1)[1]); break
        break
' "$tmp" "$name")
    warn "StatefulSet ${ns:-default}/$name has immutable-field changes — recreating (pods and PVCs kept)"
    k -n "${ns:-default}" delete statefulset "$name" --cascade=orphan --wait=true >/dev/null
  done
  k apply -f "$tmp" | sed 's/^/    /'
  rm -f "$tmp" "$err"
}

nodes_ready() { ! k get nodes --no-headers 2>/dev/null | awk '$2 != "Ready"' | grep -q . && k get nodes --no-headers >/dev/null 2>&1; }

# Wait for all nodes Ready; on failure show the kubelet's reason.
ensure_nodes_ready() {
  retry "$WAIT_TIMEOUT" 5 nodes_ready && return 0
  k get nodes -o json | jq -r '.items[] | .metadata.name + ": " +
    ([.status.conditions[] | select(.type == "Ready")][0].message // "unknown")' >&2 || true
  die "nodes still NotReady. If the reason is 'cni plugin not initialized', containerd sees no CNI config in the dir it watches (k3s + flannel-backend=none: /etc/cni/net.d, /opt/cni/bin)"
}

rollout() { # rollout <namespace> <kind/name>
  k -n "$1" rollout status "$2" --timeout="${WAIT_TIMEOUT}s"
}

# Content hash of everything that goes into an app image (apps/<name>/).
app_source_hash() { # app_source_hash <app-dir>
  (cd "$1" && find Dockerfile .dockerignore pyproject.toml config src -type f \
     ! -path '*__pycache__*' ! -name '*.pyc' ! -path '*.egg-info*' -print0 |
   sort -z | xargs -0 sha256sum | sha256sum | cut -c1-12)
}

# Image tag = source hash, so a workload only rolls when the service actually changed.
consensus_image_ref() {
  printf '%s:%s' "$CONSENSUS_IMAGE" "$(app_source_hash "$APPS_DIR/consensus")"
}
processor_image_ref() {
  printf '%s:%s' "$PROCESSOR_IMAGE" "$(app_source_hash "$APPS_DIR/telemetry-processor")"
}

# containerd_has_image <image-ref> — is the image in k3s containerd? Needs root, so it only answers
# when sudo works without a prompt (already authenticated or NOPASSWD); otherwise "unknown" (2).
containerd_has_image() {
  sudo -n true 2>/dev/null || return 2
  sudo -n k3s ctr -n k8s.io images ls -q 2>/dev/null |
    grep -qxE "(docker\.io/library/)?$(printf '%s' "$1" | sed 's/[.[\*^$]/\\&/g')"
}

# import_app_image <image-ref> <app-dir> — docker build → k3s containerd (no registry), skipped when
# this exact ref was imported before (.state/images) and containerd still has it. The record alone is
# not proof: an import that failed halfway leaves pods in ErrImageNeverPull, which the skip would then
# hide on every later run.
import_app_image() {
  local ref=$1 dir=$2 record="$STATE_DIR/images"
  mkdir -p "$STATE_DIR"
  if grep -qxF "$ref" "$record" 2>/dev/null; then
    containerd_has_image "$ref"
    case $? in
      0|2) skip "image $ref already imported"; return 0 ;;
      *) warn "image $ref is recorded as imported but missing from k3s containerd: importing again" ;;
    esac
  fi
  info "building $ref"
  docker build -q -t "$ref" "$dir" >/dev/null
  info "importing $ref into k3s containerd (sudo)"
  docker save "$ref" | as_root k3s ctr -n k8s.io images import - >/dev/null
  # sudo is authenticated at this point, so the check answers for real.
  containerd_has_image "$ref" || [[ $? -eq 2 ]] ||
    die "import of $ref reported success but the image is not in k3s containerd"
  grep -qxF "$ref" "$record" 2>/dev/null || echo "$ref" >>"$record"
  ok "image $ref imported"
}

# CloudNativePG primary of the TBMQ database, and a psql query against it (local socket, peer auth).
tbmq_db_primary() {
  k -n "$TBMQ_NAMESPACE" get pod -l cnpg.io/cluster=tbmq-db,cnpg.io/instanceRole=primary \
    -o jsonpath='{.items[0].metadata.name}'
}
tbmq_db_query() { # tbmq_db_query <sql>
  local pod
  pod=$(tbmq_db_primary) && [[ -n "$pod" ]] || { echo "no tbmq-db primary pod"; return 1; }
  k -n "$TBMQ_NAMESPACE" exec "$pod" -c postgres -- psql -d thingsboard_mqtt_broker -tAc "$1"
}

# Readiness of the operator-managed data services (pods, not just CR conditions: those can be stale
# right after hibernation / paused reconciliation ends).
strimzi_pods_ready() { # strimzi_pods_ready <namespace> <cluster> <replicas>
  local n
  n=$(k -n "$1" get pods -l "strimzi.io/cluster=$2,strimzi.io/broker-role=true" -o json 2>/dev/null |
    jq '[.items[] | select(any(.status.conditions[]?; .type == "Ready" and .status == "True"))] | length') || return 1
  [[ "$n" == "$3" ]] || { echo "$2 pods ready: ${n:-0}/$3"; return 1; }
}
kafka_pods_ready() { strimzi_pods_ready "$TBMQ_NAMESPACE" tbmq-kafka "$KAFKA_REPLICAS"; }
deploy_has_ready() { # deploy_has_ready <namespace> <deployment> — at least one ready replica
  local n
  n=$(k -n "$1" get "deploy/$2" -o jsonpath='{.status.readyReplicas}' 2>/dev/null)
  ((${n:-0} >= 1))
}
postgres_instances_ready() {
  local s
  s=$(k -n "$TBMQ_NAMESPACE" get clusters.postgresql.cnpg.io tbmq-db -o jsonpath='{.status.readyInstances}/{.spec.instances}' 2>/dev/null) || return 1
  [[ "$s" == "$POSTGRES_INSTANCES/$POSTGRES_INSTANCES" ]] || { echo "postgres instances ready: $s"; return 1; }
}

# release_lb_node_ports <namespace> <service> — drop NodePorts that a LoadBalancer Service got
# before allocateLoadBalancerNodePorts=false: the API server keeps already allocated ones.
release_lb_node_ports() {
  local patch
  patch=$(k -n "$1" get svc "$2" -o json | jq -c '
    if .spec.allocateLoadBalancerNodePorts == false then
      [.spec.ports | to_entries[] | select(.value.nodePort != null) | {op: "remove", path: "/spec/ports/\(.key)/nodePort"}]
    else [] end') || return 1
  if [[ "$patch" != "[]" ]]; then
    k -n "$1" patch svc "$2" --type=json -p "$patch" >/dev/null
    ok "released NodePorts of $1/$2"
  fi
}

# --- lifecycle helpers (make down / make up) -----------------------------------
# Strimzi cannot scale a Kafka cluster to zero: pause reconciliation, remove the broker pod sets and
# scale its operator-owned deployments (entity operator, exporter) down. PVCs (deleteClaim: false)
# and the node ids in the KafkaNodePool status are kept.
strimzi_stop() { # strimzi_stop <namespace> <cluster>
  k -n "$1" get "kafka/$2" >/dev/null 2>&1 || return 0
  k -n "$1" annotate kafka "$2" strimzi.io/pause-reconciliation=true --overwrite >/dev/null
  k -n "$1" delete strimzipodset -l "strimzi.io/cluster=$2" --ignore-not-found >/dev/null
  k -n "$1" scale deploy -l "strimzi.io/cluster=$2" --replicas=0 >/dev/null 2>&1 || true
  ok "kafka/$2 paused, pods removed"
}
strimzi_start() { # strimzi_start <namespace> <cluster> — Strimzi recreates the pods on their PVCs
  k -n "$1" get "kafka/$2" >/dev/null 2>&1 || return 0
  if [[ "$(k -n "$1" get kafka "$2" -o jsonpath='{.metadata.annotations.strimzi\.io/pause-reconciliation}')" == true ]]; then
    k -n "$1" annotate kafka "$2" strimzi.io/pause-reconciliation- >/dev/null
    info "kafka/$2: reconciliation resumed"
  fi
}
# KEDA keeps scaling a paused ScaledObject's target to the paused replica count.
keda_pause() { # keda_pause <namespace> <scaledobject>
  k -n "$1" get "scaledobject/$2" >/dev/null 2>&1 || return 0
  k -n "$1" annotate scaledobject "$2" autoscaling.keda.sh/paused-replicas=0 --overwrite >/dev/null
