# --- configuration -----------------------------------------------------------
# Precedence: environment > config.local.env > config.env defaults.
load_config() {
  local defaults="$ROOT_DIR/config.env" local_file="$ROOT_DIR/config.local.env"
  local names name
  names=$(grep -oE '\$\{[A-Z0-9_]+:=' "$defaults" | tr -d '${:=' | sort -u)
  declare -A from_env=()
  for name in $names; do
    if [[ -n "${!name+x}" && -n "${!name}" ]]; then from_env[$name]="${!name}"; fi
  done
  if [[ -f "$local_file" ]]; then
    set -a; source "$local_file"; set +a
  fi
  for name in "${!from_env[@]}"; do printf -v "$name" '%s' "${from_env[$name]}"; done
  set -a; source "$defaults"; set +a
  # shellcheck disable=SC2086
  export $names
  CONFIG_NAMES="$names"
}
load_config
export PATH="$TOOLS_BIN_DIR:$PATH"

# TBMQ admin password: configured value, else the one generated by scripts/install/70-tbmq.sh.
if [[ -z "$TBMQ_ADMIN_PASSWORD" && -s "$STATE_DIR/tbmq-admin-password" ]]; then
  TBMQ_ADMIN_PASSWORD=$(<"$STATE_DIR/tbmq-admin-password")
  export TBMQ_ADMIN_PASSWORD
fi

# --- output ------------------------------------------------------------------
if [[ -t 1 && -z "${NO_COLOR:-}" ]]; then
  C_RESET=$'\e[0m' C_BOLD=$'\e[1m' C_DIM=$'\e[2m'
  C_RED=$'\e[31m' C_GREEN=$'\e[32m' C_YELLOW=$'\e[33m' C_BLUE=$'\e[34m' C_CYAN=$'\e[36m'
else
  C_RESET='' C_BOLD='' C_DIM='' C_RED='' C_GREEN='' C_YELLOW='' C_BLUE='' C_CYAN=''
fi

step()  { printf '\n%s==> %s%s\n' "$C_BOLD$C_BLUE" "$*" "$C_RESET"; }
info()  { printf '    %s\n' "$*"; }
ok()    { printf '    %s✔%s %s\n' "$C_GREEN" "$C_RESET" "$*"; }
skip()  { printf '    %s↷ %s%s\n' "$C_DIM" "$*" "$C_RESET"; }
warn()  { printf '    %s!%s %s\n' "$C_YELLOW" "$C_RESET" "$*" >&2; }
die()   { printf '    %s✖ %s%s\n' "$C_RED" "$*" "$C_RESET" >&2; exit 1; }

trap 'rc=$?; printf "%s✖ failed (exit %s) at %s:%s: %s%s\n" "$C_RED" "$rc" "${BASH_SOURCE[0]##*/}" "$LINENO" "$BASH_COMMAND" "$C_RESET" >&2' ERR

# --- generic helpers ---------------------------------------------------------
has() { command -v "$1" >/dev/null 2>&1; }

require() {
  local missing=()
  for c in "$@"; do has "$c" || missing+=("$c"); done
  ((${#missing[@]} == 0)) || die "missing required commands: ${missing[*]} (run: make install-prereqs)"
}

# retry <timeout-seconds> <interval-seconds> <command...>
retry() {
  local timeout=$1 interval=$2; shift 2
  local deadline=$((SECONDS + timeout))
  until "$@" >/dev/null 2>&1; do
    ((SECONDS < deadline)) || return 1
    sleep "$interval"
  done
}

# Run as root, prompting for sudo only when needed.
as_root() {
  if [[ $EUID -eq 0 ]]; then "$@"; else sudo "$@"; fi
}

# Render a template, substituting only ${VARS} that appear in it.
render() {
  local tpl=$1 vars
  vars=$(grep -oE '\$\{[A-Z0-9_]+\}' "$tpl" | sort -u | tr '\n' ' ' || true)
  envsubst "$vars" <"$tpl"
}

