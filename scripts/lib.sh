  k -n "$1" get "scaledobject/$2" >/dev/null 2>&1 || return 0
  k -n "$1" annotate scaledobject "$2" autoscaling.keda.sh/paused-replicas- >/dev/null
}

# A pod gets a copy of the host resolver configuration when it starts, so after the laptop changes
# network the running CoreDNS keeps forwarding to an upstream that no longer answers: every external
# name fails inside the cluster (Grafana's plugin download, Helm chart hooks, image-less fetches).
dns_answers() { # dns_answers <server> <name>  — one A query over UDP, exit 0 when the server answers it
  python3 - "$1" "$2" <<'PY'
import random, socket, struct, sys
server, name = sys.argv[1], sys.argv[2]
query = struct.pack("!HHHHHH", random.randrange(65536), 0x0100, 1, 0, 0, 0)
query += b"".join(bytes([len(p)]) + p.encode() for p in name.split(".")) + b"\0" + struct.pack("!HH", 1, 1)
sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
sock.settimeout(5)
try:
    sock.sendto(query, (server, 53))
    answer, _ = sock.recvfrom(4096)
except OSError as e:
    sys.exit(f"{name} via {server}: {e}")
rcode, answers = answer[3] & 0xF, struct.unpack("!H", answer[6:8])[0]
sys.exit(0 if rcode == 0 and answers else f"{name} via {server}: rcode={rcode}, {answers} answers")
PY
}
cluster_dns_ip() {
  k -n kube-system get svc kube-dns -o jsonpath='{.spec.clusterIP}' 2>/dev/null
}
cluster_dns_resolves_externally() { # uses DNS_PROBE_NAME; skipped (exit 0) when the host itself cannot resolve it
  local ip
  ip=$(cluster_dns_ip) && [[ -n "$ip" ]] || return 0
  getent hosts "$DNS_PROBE_NAME" >/dev/null 2>&1 || return 0
  dns_answers "$ip" "$DNS_PROBE_NAME"
}

# A StatefulSet's volumeClaimTemplates are immutable, so changing a PVC size makes every later apply
# fail with "updates to statefulset spec for fields other than ... are forbidden". Recreating the
# StatefulSet with --cascade=orphan keeps its pods running and its PVCs (with their data) in place; the
# new StatefulSet adopts them. The existing PVC keeps its old size — local-path cannot expand a volume
# and never enforced the request anyway, since the volume is a directory on the node disk.
sts_recreate_if_storage_changed() { # sts_recreate_if_storage_changed <namespace> <statefulset> <size>
  local current
  current=$(k -n "$1" get sts "$2" -o jsonpath='{.spec.volumeClaimTemplates[0].spec.resources.requests.storage}' 2>/dev/null) || return 0
  [[ -n "$current" && "$current" != "$3" ]] || return 0
  info "$2: volumeClaimTemplate $current -> $3, recreating the StatefulSet (pods and PVCs are kept)"
  k -n "$1" delete sts "$2" --cascade=orphan >/dev/null
}

helm_revision() { # helm_revision <release> <namespace>  -> revision or 0
  helm status "$1" -n "$2" -o json 2>/dev/null | jq -r '.version // 0' || echo 0
}

# A first install that failed (a --wait timeout, for example) leaves a release with no deployed
# revision, and every later "helm upgrade --install" of it dies with "has no deployed releases".
helm_never_deployed() { # helm_never_deployed <release> <namespace>  — true when the release exists but never deployed
  local history
  history=$(helm history "$1" -n "$2" -o json 2>/dev/null) || return 1
  jq -e 'any(.[]; .status == "deployed")' <<<"$history" >/dev/null 2>&1 && return 1
  warn "release $1 never deployed (last revision: $(jq -r '.[-1].status // "unknown"' <<<"$history")) — uninstalling it first"
}

# Remove such a release so the retry installs it; releases that deployed at least once are left alone.
helm_clear_failed_install() { # helm_clear_failed_install <release> <namespace>
  helm_never_deployed "$1" "$2" || return 0
  helm uninstall "$1" -n "$2" --wait --timeout "${WAIT_TIMEOUT}s" >/dev/null 2>&1 || true
}

# --- verify helpers ----------------------------------------------------------
CHECKS_OK=0 CHECKS_FAILED=0 CHECKS_WARN=0

# check "<description>" <command...>   — command output hidden, exit status decides
check() {
  local desc=$1; shift
  local out
  if out=$("$@" 2>&1); then
    ok "$desc"; CHECKS_OK=$((CHECKS_OK + 1))
  else
    printf '    %s✖%s %s\n' "$C_RED" "$C_RESET" "$desc"
    [[ -n "$out" ]] && printf '%s\n' "$out" | tail -n 3 | sed "s/^/      ${C_DIM}/;s/\$/${C_RESET}/"
    CHECKS_FAILED=$((CHECKS_FAILED + 1))
  fi
}

# soft_check: same as check, but failures only warn
soft_check() {
  local desc=$1; shift
  if "$@" >/dev/null 2>&1; then
    ok "$desc"; CHECKS_OK=$((CHECKS_OK + 1))
  else
    warn "$desc"; CHECKS_WARN=$((CHECKS_WARN + 1))
  fi
}

checks_summary() {
  printf '\n%s%d passed%s, %s%d failed%s, %s%d warnings%s\n' \
    "$C_GREEN" "$CHECKS_OK" "$C_RESET" "$C_RED" "$CHECKS_FAILED" "$C_RESET" "$C_YELLOW" "$CHECKS_WARN" "$C_RESET"
  ((CHECKS_FAILED == 0))
}
